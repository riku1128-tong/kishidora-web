#!/usr/bin/env python3
"""Generate the SFC game data from the Safari build (repository root).

Output (data/gen):
  gdata.h     ids, counts, constants, struct types
  tables.c    item / skill / special / effect / enemy / area tables (C, copied to WRAM)
  estat.s     precomputed enemy stats per area x 面 (ROM)
  text.s      every string as glyph codes (ROM) + text.h ids
  font.bin    12-dot glyphs used by the text (+ .wid widths, .chars glyph order)
  gfx*.s      graphics (tools/make_gfx.py)
"""
import json
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
GEN = os.path.join(ROOT, 'data', 'gen')
sys.path.insert(0, os.path.join(HERE, 'data'))
sys.path.insert(0, os.path.join(HERE, 'extract'))
sys.path.insert(0, HERE)

import safari      # noqa: E402
import enemies     # noqa: E402
import text as textmod  # noqa: E402
import descs       # noqa: E402

WTYPES = ['WT_SWORD', 'WT_SPEAR', 'WT_HAMMER', 'WT_SHIELD']
RARITIES = safari.RARITY_IDS
ELEMENTS = ['EL_NONE', 'EL_FIRE', 'EL_WATER', 'EL_WOOD', 'EL_LIGHT', 'EL_DARK']
SIZES = ['SZ_S', 'SZ_M', 'SZ_L']
KINDS = ['EK_ZAKO', 'EK_BOSS', 'EK_LUCKY']
TARGETS = ['TGT_ONE', 'TGT_TWO', 'TGT_ALL']
BUFFS = ['BF_NONE', 'BF_FREE', 'BF_POWER', 'BF_CRIT']
AILS = ['AIL_NONE', 'AIL_POISON', 'AIL_PARALYZE', 'AIL_BLIND']
ABILITIES = ['', 'BA_LOCK', 'BA_DRAIN', 'BA_STDRAIN', 'BA_GUARD', 'BA_ALL']
GCS = ['GC_ALL', 'GC_ELEMENT', 'GC_RACE', 'GC_SCENE']
SCENES = ['SCN_FIELD', 'SCN_CAVE']
MATS = ['MAT_KYOUKA', 'MAT_SKYOUKA', 'MAT_HKYOUKA', 'MAT_BELL',
        'MAT_TSUME_FIRE', 'MAT_TSUME_WATER', 'MAT_TSUME_WOOD', 'MAT_TSUME_LIGHT', 'MAT_TSUME_DARK',
        'MAT_CLAW_FIRE', 'MAT_CLAW_WATER', 'MAT_CLAW_WOOD', 'MAT_CLAW_LIGHT', 'MAT_CLAW_DARK',
        'IT_FUERU', 'IT_RESET']
ROLE_ZAKO, ROLE_MID, ROLE_BOSS, ROLE_LUCKY = 0, 1, 2, 3


def cname(s):
    return re.sub(r'[^A-Za-z0-9_]', '_', s).upper()


class Gen:
    def __init__(self):
        self.s = safari.get()
        self.T = self.s.tuning
        self.h = []          # gdata.h lines
        self.c = []          # tables.c lines
        self.tx = textmod.TextDB(os.path.join(GEN, 'font.bin'))

    # ------------------------------------------------------------ helpers
    def define(self, name, v, comment=''):
        self.h.append('#define %-28s %s%s' % (name, v, ('  /* %s */' % comment) if comment else ''))

    def enum(self, prefix, names):
        for i, n in enumerate(names):
            self.define(prefix + cname(n), i)
        self.define('N_' + prefix.rstrip('_'), len(names))

    def text(self, label, s):
        self.tx.add(label, s)
        return label

    # ------------------------------------------------------------ ids
    def build_ids(self):
        s = self.s
        self.weapon_ids = [k for k, w in s.weapons.items() if w['atk'] > 1 and w['rarity'] in RARITIES]
        self.shield_ids = [k for k, w in s.shields.items() if w['rarity'] in RARITIES]
        self.item_ids = self.weapon_ids + self.shield_ids + [s.num('FUUIN_ID')]
        self.item_index = {k: i for i, k in enumerate(self.item_ids)}
        assert len(self.item_ids) < 255
        self.skill_ids = [r['id'] for r in s.tables['SKILL_TABLE']]
        self.skill_index = {k: i for i, k in enumerate(self.skill_ids)}
        self.effect_ids = list(s.effects.keys())
        self.effect_index = {k: i for i, k in enumerate(self.effect_ids)}
        self.fk = ['FK_NONE'] + sorted({e['kind'] for e in s.effects.values()} - {'FK_NONE'})
        self.races = [r['id'] for r in s.tables['RACE_TABLE']]
        self.mon_ids = [r['id'] for r in s.tables['ENEMY_TABLE']]
        self.mon_index = {k: i for i, k in enumerate(self.mon_ids)}
        self.area_ids = [r['id'] for r in s.tables['AREA_TABLE']] + [self.T['MIRAGE']['surface']['id']]
        self.area_index = {k: i for i, k in enumerate(self.area_ids)}
        h = self.h
        h.append('/* generated by tools/make_data.py - do not edit */')
        h.append('#ifndef GDATA_H\n#define GDATA_H\n#include "sfc.h"')
        self.enum('WT_', [w[3:] for w in WTYPES])
        self.enum('R_', [r[5:] for r in RARITIES])
        self.enum('EL_', [e[3:] for e in ELEMENTS])
        self.enum('SZ_', [x[3:] for x in SIZES])
        self.enum('EK_', [x[3:] for x in KINDS])
        self.enum('TGT_', [x[4:] for x in TARGETS])
        self.enum('BF_', [x[3:] for x in BUFFS])
        self.enum('AIL_', [x[4:] for x in AILS])
        self.enum('BA_', ['NONE'] + [x[3:] for x in ABILITIES[1:]])
        self.enum('GC_', [x[3:] for x in GCS])
        self.enum('SCN_', [x[4:] for x in SCENES])
        self.enum('FK_', [x[3:] for x in self.fk])
        self.enum('RC_', [x[3:] for x in self.races])
        self.enum('MAT_', [x.replace('MAT_', '').replace('IT_', 'IT_') for x in MATS])
        self.define('N_WEAPON', len(self.weapon_ids))
        self.define('N_SHIELD', len(self.shield_ids))
        self.define('N_ITEM', len(self.item_ids))
        self.define('ITEM_SHIELD0', len(self.weapon_ids))
        self.define('ITEM_FUUIN', self.item_index[s.num('FUUIN_ID')])
        self.define('ITEM_NONE', 255)
        self.define('N_SKILL', len(self.skill_ids))
        self.define('SK_NONE', 255)
        for k, i in self.skill_index.items():
            self.define(cname(k), i)
        self.define('N_SPECIAL', len(s.specials))
        self.define('N_EFFECT', len(self.effect_ids))
        for k, i in self.effect_index.items():
            self.define(cname(k), i)
        self.define('N_MON', len(self.mon_ids))
        self.define('MON_NONE', 255)
        for k, i in self.mon_index.items():
            self.define(cname(k), i)
        self.define('N_AREA', len(self.area_ids))
        for k, i in self.area_index.items():
            self.define(cname(k), i)
        for k in ['START_WEAPON', 'EQUIP_SHIELD', 'TUTORIAL_RELIEF_WEAPON', 'TUTORIAL_REWARD_SHIELD', 'SECRET_REWARD_SHIELD', 'REWARD_SHIELD_ID',
                  'TUTORIAL_SUB_WEAPON']:
            self.define('ITEM_' + k, self.item_index[s.num(k)])
        for k in ['START_SKILLS', 'TUTORIAL_RELIEF_SKILLS']:
            for i, sk in enumerate(s.num(k)[:3]):
                self.define('%s_%d' % (k[:-1], i), 255 if sk == 'SK_NONE' else self.skill_index[sk])
        for i, k in enumerate(['EASY', 'NORMAL', 'HARD', 'EXTRA', 'LUNATIC']):
            self.define('DIFF_' + k, i)
        self.define('COIN_CAP', '999999999UL')
        self.define('MIRAGE_COINS', '%dUL' % self.T['MIRAGE_COINS']['surface'])
        self.define('MIRAGE_FIRST_MAT', MATS.index(self.T['MIRAGE_FIRST_MAT']['surface']))
        self.define('MIRAGE_FIRST_MAT_N', self.T['MIRAGE_FIRST_MAT_N'])

    # ------------------------------------------------------------ constants
    def build_consts(self):
        s, T = self.s, self.T
        self.h.append('/* params.h defines (D_) */')
        for k, v in s.defines.items():
            if isinstance(v, bool):
                v = int(v)
            if isinstance(v, int):
                self.define('D_' + k, v if -32768 <= v < 65536 else '%dL' % v)
            elif isinstance(v, list) and v and all(isinstance(x, int) and not isinstance(x, bool) for x in v):
                for i, x in enumerate(v):
                    self.define('D_%s_%d' % (k, i), x if -32768 <= x < 65536 else '%dL' % x)
        for r in s.tables['KIND_TABLE']:
            for f in ('coin_min', 'coin_max', 'item_pct', 'n_pct', 'r_pct', 'sr_pct'):
                self.define('D_%s_%s' % (r['id'], f.upper()), r[f])
        self.h.append('/* tuning.gd constants (T_) */')
        for k, v in T.items():
            if isinstance(v, bool):
                v = int(v)
            if isinstance(v, int) and not isinstance(v, bool):
                if -2147483648 <= v < 4294967296:
                    self.define('T_' + k, v if -32768 <= v < 32768 else '%dL' % v)
            elif isinstance(v, list) and v and all(isinstance(x, int) and not isinstance(x, bool) for x in v) and len(v) <= 16:
                for i, x in enumerate(v):
                    self.define('T_%s_%d' % (k, i), x if -32768 <= x < 32768 else '%dL' % x)
        dr = T['DIFFICULTY_RULES']
        self.diff = ['easy', 'normal', 'hard', 'extra', 'lunatic']
        self.c.append('const DiffRule diff_rules[%d] = {' % len(self.diff))
        for k in self.diff:
            r = dr[k]
            self.c.append('  { %d, %d, %d, %d, %d },' % (r['atk'], r['heal'], r['guard'], r['just'], r['miracle']))
        self.c.append('};')

    # ------------------------------------------------------------ tables
    def ev(self, v):
        """effect v1/v2/v3 value -> number"""
        if isinstance(v, int):
            return v
        for lst in (ELEMENTS, self.races, WTYPES, SIZES, GCS, SCENES):
            if v in lst:
                return lst.index(v)
        if v in ('RC_NONE', 'EL_NOTHING', ''):
            return 255
        if v in AILS:
            return AILS.index(v)
        raise ValueError('effect value %r' % v)

    def build_tables(self):
        s, T = self.s, self.T
        c = self.c
        # weapons/shields -> one item table
        evolve = {}
        for a, b in s.tables['WEAPON_EVOLVE_TABLE'] + s.tables['SHIELD_EVOLVE_TABLE']:
            evolve[a] = b
        c.append('const Item items[N_ITEM] = {')
        names = []
        for k in self.item_ids:
            w = s.weapons.get(k)
            if w:
                to = evolve.get(k)
                to_i = self.item_index.get(to, 255) if to else 255
                c.append('  { %d, %d, %d, %d, %d, %d, %d, 0, %d },  /* %s %s */' % (
                    WTYPES.index(w['wtype']), RARITIES.index(w['rarity']), ELEMENTS.index(w['element']), w['crit'], w['stun'],
                    self.effect_index[w['effect']], w['atk'], to_i, k, w['name']))
                names.append(w['name'])
            else:
                sh = s.shields[k]
                to = evolve.get(k)
                to_i = self.item_index.get(to, 255) if to else 255
                el = T['SHIELD_EVOLVE_ELEMENT'].get(k, 'EL_NONE')
                if k not in T['SHIELD_EVOLVE_ELEMENT'] and to:   # evolve_element(): from the target's guard effect
                    fx = s.shields[to].get('effect', '')
                    for e in T['DRAGON_ELEMENTS']:
                        if fx == 'FX_GUARD_' + e[3:]:
                            el = e
                c.append('  { %d, %d, %d, 0, 0, %d, %d, %d, %d },  /* %s %s */' % (
                    3, RARITIES.index(sh['rarity']), ELEMENTS.index(el) if el in ELEMENTS else (254 if el == 'EL_ALL' else 255), self.effect_index[sh['effect']],
                    sh['hp'], sh['def'], to_i, k, sh['name']))
                names.append(sh['name'])
        c.append('};')
        for i, n in enumerate(names):
            self.text('ITEMN_%d' % i, n)
        # skills
        ail_of = {r['skill']: r['ail'] for r in s.tables['SKILL_AIL_TABLE']}
        c.append('const Skill skills[N_SKILL] = {')
        for k in self.skill_ids:
            r = s.skills[k]
            wt = WTYPES.index(r['wtype']) if r['wtype'] in WTYPES else 4
            c.append('  { %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d },  /* %s %s */' % (
                wt, r['cost'], TARGETS.index(r['target']), r['hits'], r['power'], r['stun_pct'], BUFFS.index(r['buff']), r['star'],
                r['crit_pct'], r['crit_mult'], 255 if r['race'] == 'RC_NONE' else self.races.index(r['race']), r['race_pct'], r['reset_pct'],
                AILS.index(ail_of.get(k, 'AIL_NONE')), k, r['name']))
            self.text('SKILLN_%d' % self.skill_index[k], r['name'])
            self.text('SKILLD_%d' % self.skill_index[k], '\n'.join(descs.skill(s, k)[1:]))
        c.append('};')
        # specials
        c.append('const Special specials[N_SPECIAL] = {')
        for i, r in enumerate(s.specials):
            sk = [self.skill_index.get(r[x], 255) if r[x] != 'SK_NONE' else 255 for x in ('sk1', 'sk2', 'sk3')]
            c.append('  { %d, %d, %d, %d, %d, %d },  /* %s */' % (sk[0], sk[1], sk[2], TARGETS.index(r['target']), r['hits'], r['mult'], r['name']))
            self.text('SPN_%d' % i, r['name'])
        c.append('};')
        # effects
        c.append('const Effect effects[N_EFFECT] = {')
        for k in self.effect_ids:
            e = s.effects[k]
            c.append('  { %d, %d, %d, %d },  /* %s */' % (self.fk.index(e['kind']), self.ev(e['v1']), self.ev(e['v2']), self.ev(e['v3']), k))
            self.text('FXN_%d' % self.effect_index[k], e['name'] if k != 'FX_NONE' else 'なし')
            self.text('FXD_%d' % self.effect_index[k], '\n'.join(descs.effect_body(s, k)))
        c.append('};')
        # elements strong table
        c.append('const u8 el_strong[N_EL] = { %s };' % ', '.join(
            str(ELEMENTS.index(s.elements[e]['strong'])) if s.elements[e]['strong'] in ELEMENTS else '255' for e in ELEMENTS))
        # buff values
        c.append('const u16 buff_value[N_BF] = { 0, %d, %d, %d };' % tuple(s.buffs[b]['value'] for b in BUFFS[1:]))
        # ailments
        c.append('const Ail ails[N_AIL] = {')
        for a in AILS:
            r = next(x for x in s.tables['AIL_TABLE'] if x['id'] == a)
            c.append('  { %d, %d },' % (r['pct'], r['turns']))
            self.text('AILN_%d' % AILS.index(a), r['name'] or ' ')
        c.append('};')
        # races / elements / wtypes / rarity names
        for i, r in enumerate(self.races):
            self.text('RACEN_%d' % i, s.races[r]['name'])
        for i, e in enumerate(ELEMENTS):
            self.text('ELN_%d' % i, descs.ELEMENT[e])
        for i, w in enumerate(WTYPES):
            self.text('WTN_%d' % i, descs.WTYPE[w])
        for i, r in enumerate(RARITIES):
            self.text('RARN_%d' % i, r[5:].replace('P', '+'))
        for i, m in enumerate(MATS):
            n = T['MAT_NAMES'].get(m) or (T['GOODS'][m][0] if m in T['GOODS'] else s.weapons[next(r['item'] for r in s.tables['MAT_TABLE'] if r['id'] == m)]['name'])
            self.text('MATN_%d' % i, n)
        # enemies
        sp_of = s.boss_sp
        c.append('const Enemy enemy_rows[N_MON] = {')
        for k in self.mon_ids:
            r = s.enemies[k]
            weak = r['weak'].replace('WEAK_', 'WT_')
            fx = (sp_of[k]['fx'].replace('FX_BOSS_', '') if k in sp_of else
                  {'RC_DRAGON': 'BREATH', 'RC_HUMAN': 'GIGA', 'RC_MAOU': 'DARKRAY'}.get(r['race'], 'BREATH'))
            fxs = list(T['BOSS_FX'].keys())
            c.append('  { %d, %d, %d, %d, %d, %d, %d },  /* %s %s */' % (
                KINDS.index(r['kind']), self.races.index(r['race']), ELEMENTS.index(r['element']),
                WTYPES.index(weak) if weak in WTYPES else 255, SIZES.index(r['size']),
                fxs.index(fx) if fx in fxs else 0, ABILITIES.index(s.boss_abilities.get(k, '')), k, r['name']))
            self.text('MONN_%d' % self.mon_index[k], r['name'])
            spn = sp_of[k]['sp_name'] if k in sp_of else s.races[r['race']].get('sp_name', '')
            if k in T['MEAT_ASK_MONS']:
                spn = T['MEAT_ASK_NAME']
            self.text('MONSP_%d' % self.mon_index[k], spn or ' ')
        c.append('};')
        self.define('N_BOSSFX', len(T['BOSS_FX']))
        for i, k in enumerate(T['BOSS_FX']):
            self.define('BFX_' + k, i)
        # areas
        c.append('const Area areas[N_AREA] = {')
        castle, secret = s.num('AREA_CASTLE'), s.num('AREA_SECRET')
        bgm_boss = s.num('AREA_BOSS_BGM')
        for i, k in enumerate(self.area_ids):
            mirage = k == self.T['MIRAGE']['surface']['id']
            if mirage:
                m = T['MIRAGE']['surface']
                a = {'x': m['spot'][0], 'y': m['spot'][1], 'scenery': 'SCN_CAVE', 'mid': 'MON_NONE', 'boss': 'MON_NONE',
                     'n_pct': 0, 'r_pct': 0, 'sr_pct': 0, 'coin_pct': 0, 'hp_pct': 100, 'atk_pct': 100, 'boss_pct': 100}
                name = m['name']
            else:
                a = s.areas[k]
                name = a['name']
            pool = s.zako_pool(k) if not mirage else []
            men = 1 if mirage else (s.num('CASTLE_MEN') if k == castle else (1 if k == secret else s.num('AREA_MEN')))
            tr = next((t for t in s.tables['TREASURE_TABLE'] if t['area'] == k), None)
            reward = next((r['item'] for r in s.tables['BOSS_REWARD_TABLE'] if r['area'] == k), None)
            c.append('  { %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, { %s }, %d, %d, %d },  /* %s %s */' % (
                a['x'], a['y'], SCENES.index(a['scenery']), self.mon_index.get(a['mid'], 255), self.mon_index.get(a['boss'], 255),
                a['n_pct'], a['r_pct'], a['sr_pct'], a['coin_pct'], T['COIN_DROP_PCT'].get(k, 100), men,
                1 if tr else 0, len(pool), ', '.join(str(self.mon_index[p]) for p in pool + ['MON_NONE'] * (8 - len(pool)) if p in self.mon_index) or '0',
                (tr['r_pct'] if tr else 0), (tr['sr_pct'] if tr else 0), self.item_index.get(reward, 255) if reward else 255, k, name))
            self.text('AREAN_%d' % i, name)
        c.append('};')
        # castle bosses / final
        c.append('const u8 castle_bosses[9] = { %s };' % ', '.join(str(self.mon_index[m]) for m in s.num('CASTLE_BOSSES')))
        c.append('const u8 castle_final[5] = { %s };' % ', '.join(str(self.mon_index[m]) for m in s.num('CASTLE_FINAL')))
        c.append('const u8 maou_forms[3] = { %s };' % ', '.join(str(self.mon_index[m]) for m in s.num('MAOU_FORMS')))
        noe = s.num('NO_ESCORT')
        c.append('const u8 no_escort[N_MON] = { %s };' % ', '.join('1' if m in noe else '0' for m in self.mon_ids))
        lucky = [m for m in self.mon_ids if s.enemies[m]['kind'] == 'EK_LUCKY']
        c.append('const u8 lucky_mons[%d] = { %s };' % (len(lucky), ', '.join(str(self.mon_index[m]) for m in lucky)))
        by_el = {}
        for a in s.tables['AREA_TABLE']:
            b = a.get('boss', '')
            r = s.enemies.get(b)
            if not r or r['race'] != 'RC_DRAGON' or r['element'] == 'EL_NONE':
                continue
            lst = by_el.setdefault(r['element'], [])
            if b not in lst:
                lst.append(b)
        claw = {}
        for el, ids in by_el.items():
            if len(ids) >= 2:
                claw[ids[0]] = T['CLAW_WEAK_PCT']
                claw[ids[-1]] = T['CLAW_STRONG_PCT']
        c.append('const u8 claw_pct[N_MON] = { %s };' % ', '.join(str(claw.get(m, s.num('MAT_CLAW_BOSS_PCT'))) for m in self.mon_ids))
        self.define('N_LUCKY', len(lucky))
        # candidates (drops / gacha): non-evolved, non-plus rows per (type, rarity)
        evolved = {b for a, b in s.tables['WEAPON_EVOLVE_TABLE'] + s.tables['SHIELD_EVOLVE_TABLE']}
        only = s.num('SECRET_REWARD_SHIELD')
        cand = {}
        for k in self.weapon_ids:
            w = s.weapons[k]
            if w['rarity'] not in ('RARE_NP', 'RARE_RP', 'RARE_SRP') and k not in evolved:
                cand.setdefault((WTYPES.index(w['wtype']), RARITIES.index(w['rarity'])), []).append(self.item_index[k])
        for k in self.shield_ids:
            w = s.shields[k]
            if w['rarity'] not in ('RARE_NP', 'RARE_RP', 'RARE_SRP') and k not in evolved and k != only:
                cand.setdefault((3, RARITIES.index(w['rarity'])), []).append(self.item_index[k])
        flat = []
        offs = []
        for t in range(4):
            for r in range(6):
                lst = cand.get((t, r), [])
                offs.append((len(flat), len(lst)))
                flat += lst
        c.append('const u8 cand_list[%d] = { %s };' % (len(flat), ', '.join(map(str, flat))))
        c.append('const u8 cand_off[4][6][2] = {')
        for t in range(4):
            c.append('  { %s },' % ', '.join('{ %d, %d }' % offs[t * 6 + r] for r in range(6)))
        c.append('};')
        # skill lottery per weapon type (SKILL_STAR_WEIGHT), surface skills
        weight = s.num('SKILL_STAR_WEIGHT')
        for t in range(3):
            lot = []
            for r in s.tables['SKILL_TABLE']:
                if r['wtype'] == WTYPES[t] or r['wtype'] == 'SKT_SPECIAL':
                    for _ in range(weight[r['star'] - 1]):
                        if len(lot) < 128:
                            lot.append(self.skill_index[r['id']])
            c.append('const u8 skill_lot%d[%d] = { %s };' % (t, len(lot), ', '.join(map(str, lot))))
            self.define('N_SKILL_LOT%d' % t, len(lot))
        # mats
        mt = {r['id']: r for r in s.tables['MAT_TABLE']}
        c.append('const u8 mat_up[N_MAT] = { %s };' % ', '.join(
            str(MATS.index(mt[m]['up'])) if m in mt and mt[m]['up'] in MATS else '255' for m in MATS))
