    def build_ui_text(self):
        # src/text/ui.txt (shared) first, then one ui_<lane>.txt per lane of the plan (ui_battle,
        # ui_menus, ui_inventory, ...): 'ui.txt' sorts before 'ui_*.txt', so the ids of the shared
        # texts do not move when a lane adds a file.  An id may be defined once in all of them.
        seen = {}
        for path in sorted(glob.glob(os.path.join(ROOT, 'src', 'text', 'ui*.txt'))):
            name = os.path.basename(path)
            for line in open(path, encoding='utf-8'):
                line = line.rstrip('\n')
                if not line or line.startswith('#'):
                    continue
                k, _, v = line.partition('\t')
                k = k.strip()
                assert k not in seen, '%s: %s is defined twice (also in %s)' % (name, k, seen.get(k))
                seen[k] = name
                self.text(k, v.replace('\\n', '\n'))

    def write_text(self):
        tx = self.tx
        # keep every numbered family (SKILLN_0.., MONN_0..) contiguous so code can index NAME_0 + i
        fam_order = {}
        def fam(label):
            m = re.match(r'^(.*)_(\d+)$', label)
            return (m.group(1), int(m.group(2))) if m else (label, 0)
        for label, codes, src in tx.strings:
            fam_order.setdefault(fam(label)[0], len(fam_order))
        tx.strings.sort(key=lambda r: (fam_order[fam(r[0])[0]], fam(r[0])[1]))
        for f in fam_order:
            nums = [fam(r[0])[1] for r in tx.strings if fam(r[0])[0] == f and re.match(r'^.*_\d+$', r[0])]
            if nums and nums[0] == 0:
                assert nums == list(range(len(nums))), f
        n = tx.write_font()
        self.write_text_tables(n)

    def write_text_tables(self, n):
        """text.h, data/gen/text/strings.bin + data/gen/place/text.json (strings and fonts: placed by
        tools/romplace.py) and textdata.s (text_table, segment TABLES).  Identical strings share a body."""
        import romplace
        tx = self.tx
        h = ['/* generated by tools/make_data.py */', '#ifndef TEXT_H', '#define TEXT_H']
        for i, (label, codes, src) in enumerate(tx.strings):
            h.append('#define %-24s %d' % (cname(label), i))
        h.append('#define N_TEXT %d' % len(tx.strings))
        h.append('#define N_GLYPH %d' % n)
        h.append('#endif')
        open(os.path.join(GEN, 'text.h'), 'w', encoding='utf-8').write('\n'.join(h) + '\n')
        d0 = tx.encode('0123456789')
        assert d0 == list(range(d0[0], d0[0] + 10)), 'digits must be consecutive glyphs'
        os.makedirs(os.path.join(GEN, 'text'), exist_ok=True)
        blob = bytearray()
        body_of = {}
        entries = []
        refs = []
        for label, codes, src in tx.strings:
            b = b''.join(struct.pack('<H', c) for c in codes) + b'\0\0'
            if b not in body_of:
                lab = 'tx_%d' % len(body_of)
                body_of[b] = lab
                entries.append({'label': lab, 'file': 'text/strings.bin', 'off': len(blob), 'size': len(b),
                                'kind': 'whole', 'speed': 'fast'})
                blob += b
            refs.append(body_of[b])
        open(os.path.join(GEN, 'text', 'strings.bin'), 'wb').write(blob)
        # fonts: text.s adds glyph * 24 (or * 16) to .loword(font_glyphs): each one whole in a bank
        # (the width tables are read with lda f:font_width,x: 'long')
        for lab, fn, lg in (('font_glyphs', 'font.bin', False), ('font_width', 'font.bin.wid', True),
                            ('font_glyphs_s', 'font_s.bin', False), ('font_width_s', 'font_s.bin.wid', True)):
            entries.append({'label': lab, 'file': fn, 'size': os.path.getsize(os.path.join(GEN, fn)),
                            'kind': 'whole', 'speed': 'fast', 'long': lg})
        romplace.write_manifest(GEN, 'text', entries)
        out = ['; generated by tools/make_data.py (strings and fonts: data/gen/place/text.json)',
               '.export text_table', '.exportzp FONT_DIGIT0', 'FONT_DIGIT0 = %d' % d0[0]]
        out += ['.import %s' % e['label'] for e in entries if e['label'].startswith('tx_')]
        out.append('.segment "TABLES"')
        out.append('text_table:')
        for lab in refs:
            out.append('  .word .loword(%s)\n  .byte <.bank(%s)' % (lab, lab))
        open(os.path.join(GEN, 'textdata.s'), 'w').write('\n'.join(out) + '\n')
        print('text: %d strings (%d bodies, %d B), %d glyphs' % (len(tx.strings), len(body_of), len(blob), n))

