    # ------------------------------------------------------------ dex (dex_data.gd)
    def build_dex(self):
        s, T, c = self.s, self.T, self.c
        castle, secret = s.num('AREA_CASTLE'), s.num('AREA_SECRET')
        order = []

        def add(m):
            if m and m != 'MON_NONE' and m in s.enemies and m in self.mon_index and m not in order and m != 'MON_KAKASHI':
                order.append(m)
        for a in s.tables['AREA_TABLE']:
            for m in s.pools.get(a['id'], []):
                add(m)
            add(a.get('mid', ''))
            if a['id'] == castle:
                for m in s.num('CASTLE_BOSSES') + s.num('CASTLE_FINAL') + s.num('MAOU_FORMS'):
                    add(m)
            if a['id'] == secret:
                add(s.num('AWAKEN_MON'))
            add(a.get('boss', ''))
        add(s.num('TREASURE_GUARD'))
        for r in s.tables['ENEMY_TABLE']:
            if r['kind'] == 'EK_LUCKY':
                add(r['id'])
        add(s.num('TUTORIAL_MON'))
        for r in s.tables['ENEMY_TABLE']:
            add(r['id'])
        assert len(order) == len(s.tables['ENEMY_TABLE']) == 93, len(order)
        c.append('const u8 dex_mon[N_DEX_MON] = { %s };' % ', '.join(str(self.mon_index[m]) for m in order))
        self.define('N_DEX_MON', len(order))
        # weapons: type (sword, spear, hammer), rarity, atk, id; shields: rarity, def, id
        tord = {'WT_SWORD': 0, 'WT_SPEAR': 1, 'WT_HAMMER': 2}
        wps = sorted(self.weapon_ids + [s.num('FUUIN_ID')],
                     key=lambda k: (tord[s.weapons[k]['wtype']], RARITIES.index(s.weapons[k]['rarity']), s.weapons[k]['atk'], k))
        shs = sorted(self.shield_ids, key=lambda k: (RARITIES.index(s.shields[k]['rarity']), s.shields[k]['def'], k))
        c.append('const u8 dex_item[N_DEX_ITEM] = { %s };' % ', '.join(str(self.item_index[k]) for k in wps + shs))
        self.define('N_DEX_WP', len(wps))
        self.define('N_DEX_SH', len(shs))
        self.define('N_DEX_ITEM', len(wps) + len(shs))
        # where each monster appears: AREA_TABLE bits (raw pool, mid, boss; castle forms; secret)
        mask = {m: 0 for m in self.mon_ids}
        for i, a in enumerate(s.tables['AREA_TABLE']):
            ms = list(s.pools.get(a['id'], [])) + [a.get('mid', ''), a.get('boss', '')]
            if a['id'] == castle:
                ms += s.num('CASTLE_BOSSES') + s.num('CASTLE_FINAL') + s.num('MAOU_FORMS')
            if a['id'] == secret:
                ms.append(s.num('AWAKEN_MON'))
            for m in ms:
                if m in mask:
                    mask[m] |= 1 << i
        assert len(s.tables['AREA_TABLE']) <= 16
        c.append('const u16 mon_areas[N_MON] = { %s };' % ', '.join(str(mask[m]) for m in self.mon_ids))
        # evolution: from (reverse of items[].evolve); 254 = the target is not in this game
        frm = [255] * len(self.item_ids)
        to_gone = [0] * len(self.item_ids)
        for a, b in s.tables['WEAPON_EVOLVE_TABLE'] + s.tables['SHIELD_EVOLVE_TABLE']:
            if a in self.item_index and b in self.item_index:
                frm[self.item_index[b]] = self.item_index[a]
            elif a in self.item_index:
                to_gone[self.item_index[a]] = 1
        c.append('const u8 item_evo_from[N_ITEM] = { %s };' % ', '.join(str(v) for v in frm))
        c.append('const u8 item_evo_lost[N_ITEM] = { %s };   /* evolves into an item of another world */' %
                 ', '.join(str(v) for v in to_gone))
        self.text('T_RACE_SECRET', T['SECRET_RACE_LABEL'])
        for i, t in enumerate(TARGETS):
            self.text('TGTN_%d' % i, descs.TARGET[t])
        for i, z in enumerate(SIZES):
            self.text('SZN_%d' % i, z[3:])

    # ------------------------------------------------------------ BGM routing (battle_core.c battle_bgm, dex.c)
    def build_songs(self):
        """Which song plays where, as the song ids of tools/make_audio.py (BGM_* of data/gen/audio.h):
          mon_song[m]   the monster's card (DexData.monster_bgm), which is also the song of its tower WAVE;
                        0 = none (the card keeps the map song)
          area_song[a]  the area's zako STAGEs (BattleCore.stage_bgm, kind 0)
          SONG_*        the fixed songs of battle_bgm (mid-boss, 魔王の城 10 WAVEs 1-4, its 魔王 fallback, the
                        treasure / 金策 guard)
        A web song id is a file of GameData.bgm_files after Tuning.BGM_SWAP (so BGM_ZAKO_LATE (14) plays
        15_zako_castle and BGM_ZAKO_CASTLE (15) plays 14_zako_late); the SFC id is the make_audio track of
        that file, 0 for a file the SFC lacks (07_worldmap) or -1.  The rule of battle_bgm is then run here
        on these tables for every surface STAGE (each 魔王 form on the field of 10-5), the tutorial, the
        training and every tower WAVE, and must give the song of the web stage_bgm (shipped battle_core.gd
        1648) with music in every battle; else the build stops."""
        s, T = self.s, self.T
        num = s.num
        tree = ast.parse(open(os.path.join(HERE, 'make_audio.py'), encoding='utf-8').read())
        tracks = next(ast.literal_eval(n.value) for n in tree.body if isinstance(n, ast.Assign)
                      and any(getattr(t, 'id', '') == 'BGM' for t in n.targets))
        sfc = {f.rsplit('.', 1)[0]: name for name, f, shape in tracks}
        files = {}
        for f in ('assets/bgm/bgm.json', 'assets/bgm/bgm_phone.json'):
            for k, v in json.loads(s.wb.read(f)).items():
                files[int(k)] = v
        swapped = {int(k): files.get(int(v), '') for k, v in T['BGM_SWAP'].items()}
        files.update((k, v) for k, v in swapped.items() if v)

        def song(web):
            return sfc.get(files.get(web, ''), '0')

        AT = s.tables['AREA_TABLE']
        aidx = {a['id']: i for i, a in enumerate(AT)}
        ABB, BB = num('AREA_BOSS_BGM'), T['BOSS_BGM']
        castle, secret, forms = num('AREA_CASTLE'), num('AREA_SECRET'), num('MAOU_FORMS')

        def monster_bgm(m):          # dex_data.gd 388 (surface)
            if m in BB:
                return BB[m]
            if m in forms:
                return ABB[aidx[castle]]
            if m in num('CASTLE_FINAL'):
                return T['CASTLE_LAST_WAVES_BGM']
            if m == num('AWAKEN_MON'):
                return ABB[aidx[secret]]
            for i, a in enumerate(AT):
                if a['boss'] == m:
                    return ABB[i]
            best, share = -1, 0.0
            for i, a in enumerate(AT):
                pool = s.zako_pool(a['id'])
                sh = pool.count(m) / float(max(1, len(pool)))
                if sh > share:
                    best, share = i, sh
            if best >= 0:
                return num(AT[best]['bgm'], -1)
            if any(a['mid'] == m for a in AT):
                return num('BGM_BOSS', -1)
            if s.enemies.get(m, {}).get('kind') == 'EK_LUCKY':
                return num(AT[0]['bgm'], -1)
            if m == num('TUTORIAL_MON'):
                return num(s.areas[num('TUTORIAL_AREA')]['bgm'], -1)
            return -1

        core = enemies.Core(s)

        def web_stage(area, men, stage, field, count=None):   # battle_core.gd stage_bgm (surface, not classic)
            c = core
            c.start_men(area, men)
            if count is not None:
                c.stage_count = count
            c.stage = stage
            kind = c.stage_boss_kind()
            a = s.areas[area]
            if kind == 0:
                return a['bgm_no'] if 'bgm_no' in a else num(a['bgm'])
            if c.is_treasure() or c.is_money():
                mimic = BB.get(num('TREASURE_GUARD'), num('BGM_BOSS'))
                guard = c.treasure_row(area).get('guard', num('TREASURE_GUARD')) if c.is_treasure() else num('TREASURE_GUARD')
                return BB.get(guard, mimic)
            if kind == 1:
                return num('BGM_BOSS')
            boss = ''
            if c.is_castle():
                if men != num('CASTLE_MEN'):
                    boss = num('CASTLE_BOSSES')[men - 1]
                elif stage < c.stage_count:
                    return T['CASTLE_LAST_WAVES_BGM']
                else:
                    for m in field:
                        if m in forms:
                            boss = m
            elif not c.is_secret():
                boss = a['boss']
            if boss in BB:
                return BB[boss]
            if c.is_castle() and men != num('CASTLE_MEN'):
                for i in range(aidx[castle]):
                    if AT[i]['boss'] == boss:
                        return ABB[i]
            return ABB[aidx[area]]

        mon_song = {m: song(monster_bgm(m)) if m in s.enemies else '0' for m in self.mon_ids}
        area_song = {}
        for k in self.area_ids:
            a = s.areas.get(k)
            area_song[k] = song(a['bgm_no'] if 'bgm_no' in a else num(a['bgm'])) if a else '0'
        songs = {'SONG_MID': song(num('BGM_BOSS')), 'SONG_CASTLE_WAVES': song(T['CASTLE_LAST_WAVES_BGM']),
                 'SONG_CASTLE_BOSS': song(ABB[aidx[castle]]),
                 'SONG_GUARD': song(BB.get(num('TREASURE_GUARD'), num('BGM_BOSS')))}

        # the SFC rule: battle_core.c stage_boss_kind / battle_bgm on the tables above
        trea = {r['area'] for r in s.tables['TREASURE_TABLE']}

        def sfc_stage(area, men, stage, count, field, mirage=False):
            if mirage:
                return mon_song[field[0]]
            c_castle = area == castle and men != T['MONEY_MEN']
            c_money = area == castle and men == T['MONEY_MEN']
            c_treasure = men == num('TREASURE_MEN') and area in trea
            if stage != count and not (c_castle and men == num('CASTLE_MEN')):
                kind = 0
            elif c_castle or area == secret or men == num('AREA_MEN') or c_treasure or c_money:
                kind = 2
            else:
                kind = 1 if men == num('AREA_MEN') - 1 else 0
            if kind == 0:
                return area_song[area]
            if c_treasure or c_money:
                return songs['SONG_GUARD']
            if kind == 1:
                return songs['SONG_MID']
            if not c_castle:
                return mon_song[s.areas[area]['boss']]
            if men != num('CASTLE_MEN'):
                return mon_song[num('CASTLE_BOSSES')[men - 1]]
            if stage < count:
                return songs['SONG_CASTLE_WAVES']
            r = songs['SONG_CASTLE_BOSS']
            for m in field:
                if m in forms:
                    r = mon_song[m]
            return r

        cases = []     # (what, web song, SFC song)

        def add_case(what, web, got):
            cases.append((what, song(web), got))
        for a in AT:
            k = a['id']
            if k == castle:
                mens = list(range(1, num('CASTLE_MEN') + 1)) + [T['MONEY_MEN']]
            elif k == secret:
                mens = [1]
            else:
                mens = list(range(1, num('AREA_MEN') + 1)) + ([num('TREASURE_MEN')] if k in trea else [])
            for men in mens:
                n = core.stage_count_for(k, men)
                # the SFC's stage counts (battle_core.c battle_start)
                sn = (T['MONEY_STAGES'] if men == T['MONEY_MEN'] else num('CASTLE_STAGES')) if k == castle else (
                    num('SECRET_STAGES') if k == secret else (num('TREASURE_STAGES') if men == num('TREASURE_MEN') else num('MEN_STAGES')))
                assert n == sn, (k, men, n, sn)
                for st in range(1, n + 1):
                    fields = [[f] for f in forms] if k == castle and men == num('CASTLE_MEN') and st == n else [[]]
                    for fd in fields:
                        add_case('%s %d-%d%s' % (k, men, st, ' ' + fd[0] if fd else ''),
                             web_stage(k, men, st, fd), sfc_stage(k, men, st, n, fd))
        tut = num('TUTORIAL_AREA')
        assert tut == self.area_ids[0], 'the tutorial / training rows are in the first area (map.c make_rows)'
        for st in range(1, T['TUTORIAL_STAGES'] + 1):
            add_case('tutorial %d' % st, web_stage(tut, 0, st, [], T['TUTORIAL_STAGES']), sfc_stage(tut, 1, st, T['TUTORIAL_STAGES'], []))
        add_case('training', web_stage(tut, 0, 1, [], 1), sfc_stage(tut, 1, 1, 1, []))
        for w, ent in enumerate(enemies.mirage_rush(s)):
            add_case('tower WAVE %d %s' % (w + 1, ent['mon']), web_stage(ent['home'], ent['men'], ent['stage'], [ent['mon']]),
                 sfc_stage(None, 0, 0, 0, [ent['mon']], True))
        bad = ['%s: web %s, SFC %s' % x for x in cases if x[1] != x[2] or x[2] == '0']
        if bad:
            sys.exit('battle_bgm differs from the web stage_bgm (or plays no music):\n  ' + '\n  '.join(bad))
        for k, v in songs.items():
            self.define(k, v)
        c = self.c
        c.append('/* songs (tools/make_data.py build_songs): monster card / tower WAVE (0: the map song), zako STAGEs */')
        c.append('const u8 mon_song[N_MON] = { %s };' % ', '.join(mon_song[m] for m in self.mon_ids))
        c.append('const u8 area_song[N_AREA] = { %s };' % ', '.join(area_song[k] for k in self.area_ids))
        print('songs: %d cards (%d with a song), battle_bgm == web stage_bgm on %d STAGEs / WAVEs, %d songs used' % (
            len(self.mon_ids), sum(v != '0' for v in mon_song.values()), len(cases),
            len({x[2] for x in cases} | set(mon_song.values()) - {'0'})))

    # ------------------------------------------------------------ loadout rules (src/c/loadout.c)
    def build_solo(self):
        """One weapon alone can fire a special (adventure.gd solo_ok = reachable_specials of one skill
        list; INV_SOLO, the 必殺10連 roll): a bit table by the classes of the list's hit skills
        (tools/data/loadout_model.py SoloTable), checked here against the web BFS on every ordered list
        of 1-3 skills (repeats too).  One ROM blob solo_data (data/gen/solo.bin, read with lda f: by
        src/asm/loadout.s solo_eval: 'long'):
          SOLO_KICK 0     the class of SK_KICK (kick-only lists)
          SOLO_CLS 64     class of each skill: 255 buff (hits 0), 1..K the hit skills of the specials,
                          K + 1 any other hit skill
          SOLO_MUL1 128   u16 C * c (c = 0..31), SOLO_MUL2 192: u16 C * C * c
          SOLO_WPN 256    per item id: 1 = a weapon (web solo_ok counts weapons only)
          SOLO_TAB 512    bit c0 + C c1 + C^2 c2 (classes in order, 0 = none)
          SOLO_POOL       the 必殺10連 pool: item ids of each SOLO_RAR_r in the web's weapon_order
                          (dex_data.gd weapon_order filtered by rarity: adventure.gd solo_gacha_cands)"""
        import itertools
        import romplace
        import loadout_model
        s, T = self.s, self.T
        m = loadout_model.Model(s)
        assert m.skill_ids == self.skill_ids
        st = loadout_model.SoloTable(m)
        n = bad = badk = pos = 0
        for k in (1, 2, 3):
            for l in itertools.product(range(len(self.skill_ids)), repeat=k):
                ref = bool(m.web_reach([list(l)]))
                n += 1
                pos += ref
                fires, kick = st.lookup(l)
                if fires != ref:
                    bad += 1
                if kick != m.kick_only(l):        # (needs SK_KICK to have a class of its own)
                    badk += 1
        assert not bad, 'solo table: %d of %d skill lists differ from the web BFS' % (bad, n)
        assert not badk, 'solo table: kick-only differs from battle_core.gd kick_only on %d of %d lists' % (badk, n)
        blob = bytearray(512)
        blob[0] = st.cls[m.kick]
        for i, c in enumerate(st.cls):
            blob[64 + i] = c
        for c in range(32):
            struct.pack_into('<H', blob, 128 + 2 * c, st.C * c)
            struct.pack_into('<H', blob, 192 + 2 * c, st.C * st.C * c)
        assert len(self.item_ids) <= 256
        for i, k in enumerate(self.item_ids):
            blob[256 + i] = 1 if k in s.weapons else 0
        blob += st.bits
        # the 必殺10連 pool (web DexData.weapon_order: WEAPON_TABLE without material items, sword /
        # spear / hammer, below SSR, by type, rarity, atk, id)
        mats = {r['item'] for r in s.tables['MAT_TABLE'] if r.get('item')}
        tord = {'WT_SWORD': 0, 'WT_SPEAR': 1, 'WT_HAMMER': 2}
        rows = [w for w in s.tables['WEAPON_TABLE'] if w['id'] not in mats and w['wtype'] in tord and w['rarity'] in RARITIES]
        order = [w['id'] for w in sorted(rows, key=lambda w: (tord[w['wtype']], RARITIES.index(w['rarity']), int(w['atk']), w['id']))]
        pool0 = len(blob)
        cum = 0
        rates = T['SOLO_GACHA_RATES']['surface']
        tot = sum(w for _, w in rates)
        for r, (rar, w) in enumerate(rates):
            ids = [self.item_index[k] for k in order if s.weapons[k]['rarity'] == rar]
            assert ids, rar
            cum += w
            self.define('SOLO_RAR_%d' % r, RARITIES.index(rar), rar)
            self.define('SOLO_OFF_%d' % r, len(blob) - pool0)
            self.define('SOLO_CNT_%d' % r, len(ids))
            self.define('SOLO_CUM_%d' % r, cum * 100 // tot, 'roll < this: this rarity (cumulative %)')
            blob += bytes(ids)
        assert tot == 100 and cum == 100
        self.define('SOLO_NRAR', len(rates))
        self.define('SOLO_POOL', pool0, 'offset of the 必殺10連 pool in solo_data')
        self.define('SOLO_POOL_N', len(blob) - pool0)
        self.define('SOLO_C', st.C, 'classes per skill place (K + 2)')
        self.define('SOLO_TAB_BYTES', len(st.bits))
        open(os.path.join(GEN, 'solo.bin'), 'wb').write(bytes(blob))
        romplace.write_manifest(GEN, 'solo', [
            {'label': 'solo_data', 'file': 'solo.bin', 'size': len(blob), 'kind': 'whole', 'speed': 'fast',
             'long': True}])        # loadout.s: lda f:solo_data+...,x
        print('solo: %d skill lists checked (%d fire a special), K %d, table %d B, pool %d' % (
            n, pos, st.K, len(st.bits), len(blob) - pool0))

    def build_fx_state(self):
        """desc.gd fx_state: per effect a rule byte fx_rule[] = class << 4 | parameter (FR_*: the element
        of RESO / BOOST, the weapon type of TYPE) and two texts FXS_n (the 条件つき note of COND / BOOST /
        BERSERK) and FXO_n (why RESO / TYPE / ALLSR / BOOST / BERSERK do not work), ' ' when there is none
        (tools/data/loadout_model.py fx_rule).  Called after the UI texts: the new families go last."""
        import loadout_model
        s = self.s
        for i, f in enumerate(loadout_model.FR):
            self.define(f, i)
        rule = []
        for k in self.effect_ids:
            cls, par, note, off = loadout_model.fx_rule(s, k, ELEMENTS, WTYPES)
            assert par < 16
            rule.append((loadout_model.FR.index(cls) << 4) | par)
            self.text('FXS_%d' % self.effect_index[k], note or ' ')
            self.text('FXO_%d' % self.effect_index[k], off or ' ')
        self.c.append('const u8 fx_rule[N_EFFECT] = { %s };   /* FR_* << 4 | parameter */' % ', '.join(str(v) for v in rule))

    # ------------------------------------------------------------ enemy stats
    def build_estats(self):
        s = self.s
        core = enemies.Core(s)
        castle, secret = s.num('AREA_CASTLE'), s.num('AREA_SECRET')
        blocks = []     # (area_i, men, entries)
        lucky = [m for m in self.mon_ids if s.enemies[m]['kind'] == 'EK_LUCKY']

        def ent(e, role, stage):
            return (self.mon_index[e['mon']], stage, role, e['base'], e['hp_max'], e['atk'], e['sp_atk'], e['lock_atk'],
                    e['stun_need'], e['stun_step'], e['stun_cap'], e['sp_every'],
                    (1 if e['mid'] else 0) | (2 if e['miracle_next'] else 0), ABILITIES.index(e['ability']))
        for ai, area in enumerate(self.area_ids[:-1]):
            mens = list(range(1, s.num('CASTLE_MEN') + 1)) if area == castle else ([1] if area == secret else list(range(1, s.num('AREA_MEN') + 1)))
            if core.treasure_row(area):
                mens.append(s.num('TREASURE_MEN'))
            if area == castle:
                mens.append(self.T['MONEY_MEN'])
            for men in mens:
                core.start_men(area, men)
                out = []
                for z in s.zako_pool(area):
                    core.stage = 1
                    out.append(ent(core.make_enemy(z), ROLE_ZAKO, 0))
                for z in lucky:
                    out.append(ent(core.make_enemy(z), ROLE_LUCKY, 0))
                for st in range(1, core.stage_count + 1):
                    core.stage = st
                    core.mid_def = ''
                    k = core.stage_boss_kind()
                    if not k:
                        continue
                    a = s.areas[area]
                    if core.is_castle():
                        boss = s.num('CASTLE_FINAL')[st - 1] if men == s.num('CASTLE_MEN') else s.num('CASTLE_BOSSES')[men - 1]
                    elif core.is_treasure() or core.is_money():
                        boss = s.num('TREASURE_GUARD')
                    else:
                        boss = a['boss'] if k == 2 else a['mid']
                    if k == 1:
                        core.mid_def = boss
                    e = core.make_enemy(boss)
                    out.append(ent(e, ROLE_MID if e['mid'] else ROLE_BOSS, st))
                    for f in core.forms_of(boss)[1:]:
                        out.append(ent(core.make_enemy(f), ROLE_BOSS, st))
                blocks.append((ai, men, out))
        mir = enemies.mirage_enemies(s)
        mir_block = []
        for i, e in enumerate(mir):
            mir_block.append(ent(e, ROLE_BOSS, i + 1))
        self.mirage_waves = len(mir)
        blocks.append((self.area_index[self.T['MIRAGE']['surface']['id']], 1, mir_block))
        self.define('MIRAGE_WAVES', len(mir))
        # index [area][men 0..20] -> (block offset, count), then the blocks: two blobs placed by
        # tools/romplace.py (asset.s adds the offset to .loword(estat_data): each one whole in a bank)
        idx = {}
        data = bytearray()
        for ai, men, out in blocks:
            idx[(ai, men)] = (len(data), len(out))
            for e in out:
                data += struct.pack('<BBBBIHHhHHHBBB', *e)
                data += b'\0' * (24 - struct.calcsize('<BBBBIHHhHHHBBB'))
        index = bytearray()
        for ai in range(len(self.area_ids)):
            for men in range(0, 21):
                off, n = idx.get((ai, men), (0, 0))
                index += struct.pack('<HH', off, n)
        self.write_estat(bytes(index), bytes(data))
        # same data for the native (host) test build
        hc = ['/* host test copy of estat.s */', 'const unsigned short estat_index_host[] = {']
        for ai in range(len(self.area_ids)):
            for men in range(0, 21):
                off, n = idx.get((ai, men), (0, 0))
                hc.append('  %d, %d,' % (off, n))
        hc.append('};')
        hc.append('const unsigned char estat_data_host[] = {')
        for i in range(0, len(data), 24):
            hc.append('  ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
        hc.append('};')
        os.makedirs(os.path.join(ROOT, 'tools', 'host', 'gen'), exist_ok=True)
        open(os.path.join(ROOT, 'tools', 'host', 'gen', 'estat_host.c'), 'w').write('\n'.join(hc) + '\n')
        self.define('ESTAT_SIZE', 24)
        self.define('ESTAT_MEN_MAX', 20)
        assert len(data) < 65536

