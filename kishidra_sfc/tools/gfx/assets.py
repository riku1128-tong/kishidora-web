"""Collects binary assets and writes the asm/C glue; tools/romplace.py places the blobs in ROM.

    a = Assets('gfx')
    a.add('TITLE_TILES', data, compress=True)
    a.write()        -> data/gen/gfx.s, data/gen/gfx.h, data/gen/gfx/*.bin, data/gen/place/gfx.json

Each asset gets an id ASSET_<NAME>; the asm table `<prefix>_table` (segment TABLES) has 6 bytes
per asset: address (2), bank (1), flags (1: bit0 = LZSS, bit1 = tile runs), size (2, stored size).
Identical blobs are stored once (their rows point at the same label).

Tile runs (sprite pose tiles, most 32-byte tiles empty): raw size (u16), number of runs (u8), per
run the first tile and the count of non-empty tiles (u8, u8), then those tiles.  src/asm/asset.s
unpacks it with DMA (a few hundred microseconds; LZSS took up to a frame).
"""
import os
import re
import struct

from snesgfx import lzss


def tile_runs(raw):
    """raw 4bpp tiles -> the tile-runs format (see the module doc)"""
    assert len(raw) % 32 == 0 and len(raw) <= 0xffff
    tiles = [raw[i:i + 32] for i in range(0, len(raw), 32)]
    runs, data, i = [], bytearray(), 0
    while i < len(tiles):
        if tiles[i] == bytes(32):
            i += 1
            continue
        j = i
        while j < len(tiles) and tiles[j] != bytes(32) and j - i < 255:
            j += 1
        runs.append((i, j - i))
        for t in tiles[i:j]:
            data += t
        i = j
    assert len(runs) < 256 and len(tiles) <= 256
    out = bytearray(struct.pack('<HB', len(raw), len(runs)))
    for a, n in runs:
        out += bytes((a, n))
    return bytes(out + data)


def untile_runs(blob):
    n, k = struct.unpack_from('<HB', blob, 0)
    out = bytearray(n)
    p = 3 + 2 * k
    for r in range(k):
        a, c = blob[3 + 2 * r], blob[4 + 2 * r]
        out[a * 32:(a + c) * 32] = blob[p:p + c * 32]
        p += c * 32
    return bytes(out)

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.normpath(os.path.join(HERE, '..', '..', 'data', 'gen'))


class Assets:
    def __init__(self, prefix, banks=None):
        self.prefix = prefix          # (banks: no longer used, tools/romplace.py places the blobs)
        self.items = []         # (name, blob, flags)
        self.names = set()
        self.consts = []

    def add(self, name, data, compress=True, tiles=False):
        name = re.sub(r'[^A-Za-z0-9_]', '_', name).upper()
        assert name not in self.names, name
        self.names.add(name)
        flags = 0
        blob = bytes(data)
        if tiles:
            blob = tile_runs(blob)
            flags |= 2
            compress = False
        if compress and len(blob) > 64:
            z = lzss(blob)
            if len(z) < len(blob):
                blob = z
                flags |= 1
        if len(blob) > 0x8000:
            raise ValueError('%s is larger than a bank (%d)' % (name, len(blob)))
        self.items.append((name, blob, flags))
        return len(self.items) - 1

    def const(self, name, value):
        self.consts.append((name, value))

    def size(self):
        return sum(len(b) for _, b, _ in self.items)

    def write(self):
        """data/gen/<prefix>/*.bin, data/gen/place/<prefix>.json (tools/romplace.py places them),
        data/gen/<prefix>.s (the asset table, segment TABLES) and data/gen/<prefix>.h.
        Identical blobs are stored once (the table rows point at the same label)."""
        import sys
        sys.path.insert(0, os.path.normpath(os.path.join(HERE, '..')))
        import romplace
        d = os.path.join(GEN, self.prefix)
        os.makedirs(d, exist_ok=True)
        for f in os.listdir(d):
            os.remove(os.path.join(d, f))
        entries = []
        label_of = {}
        by_blob = {}
        for name, blob, flags in self.items:
            # LZSS / tile runs are unpacked by the CPU: FastROM; raw data is DMA'd: any bank
            speed = 'fast' if flags & 3 else 'any'
            if blob in by_blob:
                e = by_blob[blob]
                label_of[name] = e['label']
                if speed == 'fast':
                    e['speed'] = 'fast'
                continue
            fn = '%s/%s.bin' % (self.prefix, name.lower())
            open(os.path.join(GEN, fn), 'wb').write(blob)
            lab = '%s_%s' % (self.prefix, name.lower())
            e = {'label': lab, 'file': fn, 'size': len(blob), 'kind': 'whole', 'speed': speed}
            entries.append(e)
            by_blob[blob] = e
            label_of[name] = lab
        romplace.write_manifest(GEN, self.prefix, entries)
        asm = ['; generated by tools/gfx/assets.py (blobs: data/gen/place/%s.json)' % self.prefix,
               '.export %s_table' % self.prefix]
        asm += ['.import %s' % e['label'] for e in entries]
        asm.append('.segment "TABLES"')
        asm.append('%s_table:' % self.prefix)
        for name, blob, flags in self.items:
            lab = label_of[name]
            asm.append('  .word .loword(%s)\n  .byte <.bank(%s), %d\n  .word %d' % (lab, lab, flags, len(blob)))
        open(os.path.join(GEN, self.prefix + '.s'), 'w').write('\n'.join(asm) + '\n')
        h = ['/* generated by tools/gfx/assets.py */', '#ifndef %s_H' % self.prefix.upper(), '#define %s_H' % self.prefix.upper()]
        for i, (name, blob, flags) in enumerate(self.items):
            h.append('#define ASSET_%-28s %d' % (name, i))
        for name, v in self.consts:
            h.append('#define %-34s %s' % (name, v))
        h.append('#define N_%s_ASSETS %d' % (self.prefix.upper(), len(self.items)))
        h.append('#endif')
        open(os.path.join(GEN, self.prefix + '.h'), 'w').write('\n'.join(h) + '\n')
        used = sum(e['size'] for e in entries)
        print('%s: %d assets, %.1f KB (%d identical stored once)' % (self.prefix, len(self.items), used / 1024,
                                                                     len(self.items) - len(entries)))
